/*
 * Абстрактний клас Figure.
 * Є батьківським класом для всіх геометричних фігур.
 */
public abstract class Figure {

    // Конструктор, який викликається при створенні дочірнього об'єкта
    public Figure() {
        // Виведення спільного повідомлення для всіх фігур
        System.out.println("Об'єкт створено");
    }

    // Абстрактний метод для обчислення площі фігури
    // Реалізується окремо в кожному дочірньому класі
    public abstract double calculateArea();
}
